"""The public data quality report, rendered as Markdown."""

from __future__ import annotations

from collections import Counter
from typing import Any


def _v(x: Any) -> Any:
    return x["v"] if isinstance(x, dict) and "v" in x else x


def quality_markdown(q: dict[str, Any], version: str) -> str:
    s = q["summary"]
    lines = [
        "# Redshift data quality report",
        "",
        f"Dataset version `{version}`. Generated by `python -m redshift.build` from the raw files listed in "
        "`data/raw/MANIFEST.json`. Every flag below names the file, line, column and raw value. Flags never "
        "change a value: anomalous cells are kept verbatim and set to null.",
        "",
        "## Summary",
        "",
        "| Measure | Count |",
        "| --- | ---: |",
        f"| Tests in the canonical table | {_v(s['tests'])} |",
        f"| Experiment tables | {_v(s['tables'])} |",
        f"| Investigations with tables | {_v(s['investigations_with_tables'])} |",
        f"| Investigations described | {_v(s['investigations_total'])} |",
        f"| Exact duplicate rows removed | {_v(s['duplicates_removed'])} |",
        f"| Blank rows excluded | {_v(s['blank_rows_excluded'])} |",
        f"| Non-test rows excluded (listed below) | {_v(s['non_test_rows_excluded'])} |",
        f"| Flags | {_v(s['flags'])} |",
        f"| Numbers checked for provenance | {q['provenance_coverage']['numbers_checked']} |",
        f"| Provenance coverage | {q['provenance_coverage']['percent']}% |",
        "",
        "## Flags by code",
        "",
        "| Code | Severity | Count | Meaning |",
        "| --- | --- | ---: | --- |",
    ]
    by_code = Counter(f["code"] for f in q["flags"])
    for code, n in sorted(by_code.items(), key=lambda t: (-t[1], t[0])):
        d = q["flag_definitions"][code]
        lines.append(f"| `{code}` | {d['severity']} | {n} | {d['description']} |")
    lines += [
        "",
        "## Reconciliation (rows in = tests out + duplicates + blanks + non-test rows)",
        "",
        "| Table | Records in | Tests out | Duplicates | Blank | Non-test | Balanced |",
        "| --- | ---: | ---: | ---: | ---: | ---: | --- |",
    ]
    for r in q["reconciliation"]:
        lines.append(
            f"| `{r['table_file'].split('/')[-1]}` | {r['records_in']} | {r['tests_out']} | "
            f"{r['duplicates_removed']} | {r['blank_excluded']} | {r['non_test_excluded']} | "
            f"{'yes' if r['balanced'] else 'NO'} |"
        )
    lines += [
        "",
        "## Golden checks",
        "",
        "| Check | Expected | Actual | Status | Explanation |",
        "| --- | --- | --- | --- | --- |",
    ]
    for g in q["goldens"]["results"]:
        lines.append(
            f"| {g['description']} | {g['expected']} | {g['actual']} | {g['status'].replace('_', ' ')} | "
            f"{g['explanation'] or ''} |"
        )
    fs = q["findings"]
    lines += [
        "",
        "## Paper findings",
        "",
        f"Drafted: {fs['drafted']}. Verified by a named team member: {len(fs['verified'])}. "
        f"Awaiting verification: {len(fs['awaiting_verification'])}. Rejected by reviewer: "
        f"{len(fs['rejected_by_reviewer'])}. Failed automatic quote checks: {len(fs['failed_checks'])}.",
        "",
    ]
    for f in fs["failed_checks"]:
        lines.append(f"- `{f['id']}`: {'; '.join(f['problems'])}")
    lines += [
        "",
        "## Every flag",
        "",
        "| ID | Code | Investigation | File | Lines | Column | Raw | Detail | Action |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]

    def cell(x: Any) -> str:
        t = "" if x is None else str(x)
        return t.replace("|", "\\|").replace("\n", " ")[:160]

    for f in q["flags"]:
        rows = f["rows"]
        rtxt = ", ".join(map(str, rows[:8])) + (" ..." if len(rows) > 8 else "")
        lines.append(
            f"| {f['id']} | `{f['code']}` | {f['investigation_id']} | `{cell((f['file'] or '').split('/')[-1])}` | "
            f"{rtxt} | {cell(f['column'])} | {cell(f['raw'])} | {cell(f['detail'])} | {cell(f['action'])} |"
        )
    return "\n".join(lines) + "\n"
